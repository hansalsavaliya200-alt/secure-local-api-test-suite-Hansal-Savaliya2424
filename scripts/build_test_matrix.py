"""Builds docs/test-matrix.md from REAL results: a pytest JUnit XML run plus docs/evidence/*.
Run:  python scripts/build_test_matrix.py      (it runs pytest itself)
"""
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML = ROOT / "docs" / "evidence" / "junit.xml"
subprocess.run([sys.executable, "-m", "pytest", "-q", "--tb=short", f"--junitxml={XML}"], cwd=ROOT, check=False,
               stdout=subprocess.DEVNULL)
results = {}
for case in ET.parse(XML).getroot().iter("testcase"):
    name = case.get("name").split("[")[0]
    bad = case.find("failure") is not None or case.find("error") is not None
    results[name] = results.get(name, True) and not bad

# (category, test, scenario, expected)
CURATED = [
    ("Normal", "test_login_success_returns_bearer_token", "Valid login", "200 and a bearer token"),
    ("Normal", "test_owner_can_read_own_ticket", "User reads own ticket", "200"),
    ("Normal", "test_status_change_by_role", "Agent/admin change ticket status", "200 for agent and admin"),
    ("Normal", "test_delete_ticket_is_admin_only", "Admin deletes a ticket", "204 for admin"),
    ("Failure", "test_login_wrong_password_is_401", "Wrong password", "401, generic message"),
    ("Failure", "test_protected_route_without_token_is_401", "No token on a protected route", "401"),
    ("Failure", "test_user_cannot_read_another_users_ticket", "User reads someone else's ticket", "404 (not 403)"),
    ("Failure", "test_admin_users_list_by_role", "User/agent list accounts", "403 for user and agent"),
    ("Failure", "test_user_cannot_make_themselves_admin", "Privilege escalation attempt", "403, role unchanged"),
    ("Failure", "test_tampered_token_is_401", "Modified JWT", "401"),
    ("Failure", "test_unsigned_alg_none_token_is_refused", "JWT with alg=none", "401"),
    ("Failure", "test_expired_token_is_401", "Expired JWT", "401"),
    ("Failure", "test_login_is_limited_after_five_attempts", "6th login attempt in 60 s", "429 with Retry-After"),
    ("Failure", "test_wrong_content_type_is_415", "Form data instead of JSON", "415"),
    ("Failure", "test_invalid_ticket_bodies_are_rejected", "Unknown field, empty title, wrong types", "422"),
    ("Edge", "test_title_length_boundaries", "Title of 100 vs 101 characters", "100 accepted, 101 rejected"),
    ("Edge", "test_description_length_boundaries", "Description of 1000 vs 1001 characters", "1000 accepted, 1001 rejected"),
    ("Edge", "test_oversized_body_is_413", "Body above the size limit", "413"),
    ("Edge", "test_malformed_ticket_ids_are_404_not_500", "Ticket ID that is not a UUID", "404, no crash"),
    ("Edge", "test_limit_resets_after_the_window", "Wait out the 60 s window (fake clock)", "Login allowed again"),
    ("Edge", "test_forged_forwarding_header_cannot_bypass_the_limit", "New X-Forwarded-For on each attempt", "Still limited (429)"),
    ("Edge", "test_admin_cannot_remove_own_admin_role", "Last admin demotes themselves", "409"),
    ("Edge", "test_role_is_read_from_the_server_not_the_token", "Role changed after token was issued", "New role applies at once"),
]
lines = ["# Test matrix", "",
         "Generated by `scripts/build_test_matrix.py` from a real pytest run (`docs/evidence/junit.xml`). "
         "Nothing here is typed in by hand except the scenario text and the expected value; "
         "the **Actual** column comes from the run.", "",
         "## A. Selected tests: expected vs actual", "",
         "| # | Type | Scenario | Expected | Actual | Test |", "|---|------|----------|----------|--------|------|"]
for i, (kind, test, scenario, expected) in enumerate(CURATED, 1):
    if test not in results:
        raise SystemExit(f"unknown test name {test}")
    lines.append(f"| {i} | {kind} | {scenario} | {expected} | {'PASS' if results[test] else 'FAIL'} | `{test}` |")
passed = sum(results.values())
lines += ["", f"All {len(results)} test functions: **{passed} pass, {len(results) - passed} fail** "
          "(parametrised cases are grouped under their function name).", "",
          "## B. Retest after a fix", ""]
mut = json.loads((ROOT / "docs/evidence/mutation-results.json").read_text())
lines += ["### B1. Mutation experiment (tests must fail when a control is removed)", "",
          "A weakness was inserted into a **temporary copy** of the code, the suite was run, then the real code was retested.", "",
          "| Weakness inserted | Tests that failed | Detected |", "|---|---|---|"]
for m in mut["mutations"]:
    lines.append(f"| {m['weakness']} | {len(m['tests_that_failed'])} | {'yes' if m['detected'] else 'NO'} |")
lines += ["", f"Retest on the unmodified code: {mut['retest_on_real_code'].get('summary', mut['retest_on_real_code'])}", "",
          "### B2. A real failure found by the live demo, then fixed", "",
          "| Step | Result |", "|---|---|",
          "| Demo client against `uvicorn` with default settings | forged `X-Forwarded-For` check **FAILED** (expected 429, got 401) |",
          "| Cause | uvicorn's default `--proxy-headers` rewrote the client address from the forged header, so the limiter saw a new client each time |",
          "| Fix | start the server with `--no-proxy-headers` (documented in the README) |",
          "| Retest | the same check **PASSED** (429); all demo checks passed |",
          "",
          "Evidence: `docs/evidence/xff-before-after.txt`, `docs/evidence/demo-output.txt`.",
          "The unit tests could not catch this, because `TestClient` bypasses uvicorn. This is why the live demo is part of the test method.", ""]
(ROOT / "docs" / "test-matrix.md").write_text("\n".join(lines), encoding="utf-8")
print("wrote docs/test-matrix.md;", passed, "of", len(results), "pass")
